#!/usr/bin/env python3
"""Generate docs/side-by-side.md from the five everyday examples.

Each example marks every task with `BEGIN <task-id>` / `END <task-id>` comments
(docs/library-api.md §7). This script pulls the code between the markers and lays the
five languages out task by task, so the same everyday job can be compared across
languages and against each language's native date/time API.

Usage:
  python3 tools/side_by_side.py            write docs/side-by-side.md
  python3 tools/side_by_side.py --check    fail if docs/side-by-side.md is out of date
"""
from __future__ import annotations

import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "side-by-side.md"

LANGUAGES = [
    # (name, fence language, glob relative to the repo root, native API)
    ("C#", "csharp", "implementations/csharp/examples/Everyday/*.cs", "DateOnly, DateTime, DateTimeOffset, TimeZoneInfo"),
    ("Java", "java", "implementations/java/src/examples/java/**/Everyday*.java", "java.time"),
    ("Python", "python", "implementations/python/examples/everyday*.py", "datetime, zoneinfo"),
    ("TypeScript", "typescript", "implementations/typescript/examples/everyday*.ts", "Date, Intl"),
    ("Rust", "rust", "implementations/rust/examples/everyday*.rs", "chrono, chrono-tz"),
]

SECTIONS = [
    ("1. Now", [("now", "Now")]),
    ("2. A date", [("a-date", "5 November 2026"), ("weekday-week", "Day of week and ISO week")]),
    ("3. Invalid dates", [("feb-30", "30 February 2026")]),
    ("4. Adding", [("add-days", "5 Nov + 30 days"), ("month-end", "31 Jan 2026 + 1 month")]),
    ("5. Days between", [("days-between", "5 Nov → 25 Dec"), ("compare-dates", "Which comes first")]),
    ("6. Times and date-times", [("time-of-day", "09:30"), ("datetime-plus-hours", "23:30 + 2 hours")]),
    ("7. Parsing with offsets", [("parse-offsets", "Z vs +00:00")]),
    ("8. Time zones", [("meeting-in-paris", "09:00 in Paris, seen from New York")]),
    ("9. DST gap", [("dst-gap", "02:30 on 8 March 2026 in New York")]),
    ("10. DST overlap", [("dst-overlap", "01:30 on 1 November 2026 in New York")]),
    ("11. Timestamps", [("timestamps", "Exact fractions and differences")]),
    ("12. Durations vs periods", [("day-vs-24h", "One day vs 86,400 seconds across DST")]),
    ("13. Ranges", [("ranges", "November, open-ended and unknown ends")]),
    ("14. Round trip", [("round-trip", "Native → UTV → native")]),
]

MARKER = re.compile(r"^\s*(?://|#)\s*(BEGIN|END)\s+([a-z0-9-]+)\s*$")


def extract(files: list[Path]) -> dict[str, str]:
    """Map task id -> dedented code between its markers, across the given files."""
    tasks: dict[str, str] = {}
    for path in files:
        current: str | None = None
        lines: list[str] = []
        for line in path.read_text(encoding="utf-8").splitlines():
            m = MARKER.match(line)
            if m and m.group(1) == "BEGIN":
                if current is not None:
                    raise SystemExit(f"{path}: BEGIN {m.group(2)} inside {current}")
                current, lines = m.group(2), []
            elif m and m.group(1) == "END":
                if current != m.group(2):
                    raise SystemExit(f"{path}: END {m.group(2)} does not close {current}")
                if current in tasks:
                    raise SystemExit(f"{path}: task {current} appears twice")
                tasks[current] = textwrap.dedent("\n".join(lines)).strip("\n")
                current = None
            elif current is not None:
                lines.append(line)
        if current is not None:
            raise SystemExit(f"{path}: BEGIN {current} is never closed")
    return tasks


def render() -> str:
    found = {}
    for name, _, pattern, _ in LANGUAGES:
        files = sorted(ROOT.glob(pattern))
        found[name] = extract(files) if files else {}

    out = [
        "# Side by side: everyday date/time code in five languages",
        "",
        "<!-- Generated by tools/side_by_side.py from the everyday examples. Do not edit by hand. -->",
        "",
        "Each task shows the language's own date/time API next to UTV, exactly as the code appears",
        "in that language's `everyday` example. The trailing comments are the output; each library's",
        "snapshot test checks them. Rows marked ‡ depend on the host (its clock or time zone database).",
        "",
        "| Language | Example | Native API compared |",
        "|---|---|---|",
    ]
    for name, _, pattern, native in LANGUAGES:
        out.append(f"| {name} | `{pattern}` | {native} |")
    out.append("")

    missing: list[str] = []
    for section, tasks in SECTIONS:
        out += [f"## {section}", ""]
        for task_id, title in tasks:
            out += [f"### {title}", ""]
            for name, fence, _, _ in LANGUAGES:
                code = found[name].get(task_id)
                if code is None:
                    missing.append(f"{name}:{task_id}")
                    continue
                out += [f"**{name}**", "", f"```{fence}", code, "```", ""]
    if missing:
        out += ["## Missing", "", "These tasks have no marked code yet: " + ", ".join(missing), ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/side-by-side.md is out of date; run python3 tools/side_by_side.py")
            return 1
        print("docs/side-by-side.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
